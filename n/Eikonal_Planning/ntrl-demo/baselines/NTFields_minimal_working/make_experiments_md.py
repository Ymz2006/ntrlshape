"""Collect the NTFields 3-D shape runs into ``../../experiments_ntfields.md``.

Scans the output root written by ``train_3dshape_all.sh`` and emits one row per
environment -- checkpoint path, epochs and final training loss -- in the same
env order as the main repo's ``../../experiments_ours.md``.  Re-run it at any
time; environments that have not finished training yet are listed as pending.

Where ``3d_plan.py`` has also inferred paths for an environment (its
``plan_summary.txt`` under ``--planPath``), the row gains that model's success
rate, per-case planning time and path length -- mean +/- sd -- in the same form
and the same metrics as ``../../experiments_rrt_connect.md``, so the two tables can
be read side by side.  Environments with no planning run yet show ``--``.

``--tightPlanPath`` adds the last column: the same success rate re-measured on
the ``<env>_tight`` test sets (``3d_plan_all.sh`` with ``SUFFIX=_tight``), which
sample start and goal poses at ``--offset 0.005`` instead of 0.02.  The column
layout then matches ``../../experiments_metric_ntfields.md`` row for row.

    python make_experiments_md.py
"""

import argparse
import os
import re
import glob

ENVS = [
    'rectangle_env1', 'Lshape3d_env1', 'Fshape3d_env1', 'Ashape3d_env1', 'Vshape3d_env1', '4shape3d_env1',
    'rectangle_env2', 'Lshape3d_env2', 'Fshape3d_env2', 'Ashape3d_env2', 'Vshape3d_env2', '4shape3d_env2',
    'rectangle_env3', 'Lshape3d_env3', 'Fshape3d_env3', 'Ashape3d_env3', 'Vshape3d_env3', '4shape3d_env3',
    'rectangle_env4', 'Lshape3d_env4', 'Fshape3d_env4', 'Ashape3d_env4', 'Vshape3d_env4', '4shape3d_env4',
    # Present as datasets but absent from the main repo's ../../experiments_ours.md.
    'Tshape3d_env1', 'Lcouch_Corozal',
]

# The 2-D section: SE(2) cells generated by preprocess_obj.py --2d over the four
# planar mazes (2denv1 12 bodies, 2denv2 13, 2denv3 6, 2denv4 8), seven shapes each.
# Same network and trainer as the 3-D rows -- only the configuration space differs,
# with z / rx / ry pinned to 0 -- so they tabulate in the same columns.
# All four envs x all seven shapes = 28 cells.  The (Tshape3d, 2denv4) cell predates
# the env-tag naming and lives on disk as 'Tshape3d_env4'; DIR_ALIAS maps the cell
# name used here back to that directory, so the row reads with its siblings instead
# of hiding among the 3-D env4 rows.
ENVS_2D = [
    'rectangle_2denv1', 'Lshape3d_2denv1', 'Fshape3d_2denv1', 'Ashape3d_2denv1',
    'Vshape3d_2denv1', '4shape3d_2denv1', 'Tshape3d_2denv1',
    'rectangle_2denv2', 'Lshape3d_2denv2', 'Fshape3d_2denv2', 'Ashape3d_2denv2',
    'Vshape3d_2denv2', '4shape3d_2denv2', 'Tshape3d_2denv2',
    'rectangle_2denv3', 'Lshape3d_2denv3', 'Fshape3d_2denv3', 'Ashape3d_2denv3',
    'Vshape3d_2denv3', '4shape3d_2denv3', 'Tshape3d_2denv3',
    'rectangle_2denv4', 'Lshape3d_2denv4', 'Fshape3d_2denv4', 'Ashape3d_2denv4',
    'Vshape3d_2denv4', '4shape3d_2denv4', 'Tshape3d_2denv4',
]

# Cell name -> on-disk directory, where the two differ.
DIR_ALIAS = {'Tshape3d_2denv4': 'Tshape3d_env4'}


def env_dir(env):
    return DIR_ALIAS.get(env, env)


def hms(seconds):
    """'1h 02m 03s' from a float count of seconds."""
    total = int(round(seconds))
    return '{}h {:02d}m {:02d}s'.format(total // 3600, total % 3600 // 60, total % 60)

parser = argparse.ArgumentParser(description='Write the NTFields experiments table.')
parser.add_argument('--modelPath', default='./outputs/3dshape')
parser.add_argument('--planPath', default='./outputs/3dplan',
                    help='Root of the 3d_plan.py runs; <planPath>/<env>/'
                         'plan_summary.txt supplies the path-inference columns.')
parser.add_argument('--tightPlanPath', default='./outputs/3dplan_tight',
                    help='Root of the SUFFIX=_tight 3d_plan.py runs; '
                         '<tightPlanPath>/<env>_tight/plan_summary.txt supplies '
                         'the Valid (tight) column.')
parser.add_argument('--epochs', type=int, default=4000)
parser.add_argument('--out', default='../../experiments_ntfields.md')
args = parser.parse_args()

CKPT = 'Model_Epoch_{:05d}_ValLoss_*.pt'.format(args.epochs)


def run_dir(env):
    """Newest run folder for ``env`` that reached the target epoch count."""
    hits = sorted(glob.glob(os.path.join(args.modelPath, env_dir(env), CKPT)),
                  key=os.path.getmtime)
    return os.path.dirname(hits[-1]) if hits else None


def log_stats(env):
    """(final loss, train seconds) parsed from the per-env training log."""
    path = os.path.join(args.modelPath, 'logs', env_dir(env) + '.log')
    loss = seconds = None
    if os.path.exists(path):
        with open(path, errors='ignore') as fh:
            for line in fh:
                m = re.match(r'Epoch = (\d+) -- Loss = ([\d.e+-]+)', line)
                if m and int(m.group(1)) == args.epochs:
                    loss = float(m.group(2))
                m = re.search(r'Training time: ([\d.]+)s', line)
                if m:
                    seconds = float(m.group(1))
    return loss, seconds


def plan_stats(root, name):
    """Path-inference numbers for ``<root>/<name>/plan_summary.txt``.

    Returns (success_rate, time_mean, time_std, len_mean, len_std, n_success,
    n_cases) with ``None`` when that run does not exist yet.
    """
    path = os.path.join(root, name, 'plan_summary.txt')
    if not os.path.exists(path):
        return None
    keys = ('success_rate', 'time_mean', 'time_std',
            'path_length_mean', 'path_length_std', 'successes',
            'test_cases_scored')
    got = {}
    with open(path, errors='ignore') as fh:
        for line in fh:
            m = re.match(r'(\w+)\s*:\s*([\d.eE+-]+)', line)
            if m and m.group(1) in keys and m.group(1) not in got:
                got[m.group(1)] = float(m.group(2))
    if not all(k in got for k in keys):
        return None
    return (got['success_rate'], got['time_mean'], got['time_std'],
            got['path_length_mean'], got['path_length_std'],
            int(got['successes']), int(got['test_cases_scored']))


rows, rows_2d, pending, planned, tight_planned = [], [], [], [], []
for env in ENVS + ENVS_2D:
    sink = rows_2d if env in ENVS_2D else rows
    folder = run_dir(env)
    if folder is None:
        # No epoch-N checkpoint yet.  Still emit the row so the table lists every
        # cell of the benchmark rather than only the finished ones; a run that is
        # under way contributes its elapsed training seconds from the log, which
        # is why Train Time (s) can be populated while Model is still '--'.
        pending.append(env)
        loss, seconds = log_stats(env)
        sink.append((env, None,
                     '{:.4e}'.format(loss) if loss is not None else '--',
                     '{:.0f}'.format(seconds) if seconds is not None else '--',
                     hms(seconds) if seconds is not None else '--',
                     '--', '--', '--', '--'))
        continue
    loss, seconds = log_stats(env)
    plan = plan_stats(args.planPath, env_dir(env))
    if plan is None:
        rate = ptime = plen = '--'
    else:
        rate = '{:.1%} ({}/{})'.format(plan[0], plan[5], plan[6])
        ptime = '{:.3f} ± {:.3f}'.format(plan[1], plan[2])
        plen = '{:.3f} ± {:.3f}'.format(plan[3], plan[4])
        planned.append(env)
    tight = plan_stats(args.tightPlanPath, env_dir(env) + '_tight')
    if tight is None:
        trate = '--'
    else:
        trate = '{:.1%} ({}/{})'.format(tight[0], tight[5], tight[6])
        tight_planned.append(env)
    sink.append((env,
                 os.path.join(folder, 'latest.pt'),
                 '{:.4e}'.format(loss) if loss is not None else '--',
                 '{:.0f}'.format(seconds) if seconds is not None else '--',
                 hms(seconds) if seconds is not None else '--',
                 rate, ptime, plen, trate))

