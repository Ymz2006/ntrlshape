parser.add_argument('--epochs', type=int, default=4000)
parser.add_argument('--out', default='../../experiments_ntfields.md')
args = parser.parse_args()

CKPT = 'Model_Epoch_{:05d}_ValLoss_*.pt'.format(args.epochs)


def run_dir(env):
    """Newest run folder for ``env`` that reached the target epoch count."""
    hits = sorted(glob.glob(os.path.join(args.modelPath, env_dir(env), CKPT)),
                  key=os.path.getmtime)
    return os.path.dirname(hits[-1]) if hits else None


def log_stats(env):
    """(final loss, train seconds) parsed from the per-env training log."""
    path = os.path.join(args.modelPath, 'logs', env_dir(env) + '.log')
    loss = seconds = None
    if os.path.exists(path):
        with open(path, errors='ignore') as fh:
            for line in fh:
                m = re.match(r'Epoch = (\d+) -- Loss = ([\d.e+-]+)', line)
                if m and int(m.group(1)) == args.epochs:
                    loss = float(m.group(2))
                m = re.search(r'Training time: ([\d.]+)s', line)
                if m:
                    seconds = float(m.group(1))
    return loss, seconds


def plan_stats(root, name):
    """Path-inference numbers for ``<root>/<name>/plan_summary.txt``.

    Returns (success_rate, time_mean, time_std, len_mean, len_std, n_success,
    n_cases, split) with ``None`` when that run does not exist yet.  ``split``
    is (trans_mean, trans_std, rot_mean, rot_std) -- the translation / rotation
    halves of the OMPL length that 3d_plan.py has written since 2026-09-12 --
    or ``None`` for an older summary.
    """
    path = os.path.join(root, name, 'plan_summary.txt')
    if not os.path.exists(path):
        return None
    keys = ('success_rate', 'time_mean', 'time_std',
            'path_length_mean', 'path_length_std', 'successes',
            'test_cases_scored')
    split_keys = ('trans_length_mean', 'trans_length_std',
                  'rot_length_mean', 'rot_length_std')
    got = {}
    with open(path, errors='ignore') as fh:
        for line in fh:
            m = re.match(r'(\w+)\s*:\s*([\d.eE+-]+)', line)
            if m and m.group(1) in keys + split_keys and m.group(1) not in got:
                got[m.group(1)] = float(m.group(2))
    if not all(k in got for k in keys):
        return None
    split = (tuple(got[k] for k in split_keys)
             if all(k in got for k in split_keys) else None)
    return (got['success_rate'], got['time_mean'], got['time_std'],
            got['path_length_mean'], got['path_length_std'],
            int(got['successes']), int(got['test_cases_scored']), split)


rows, rows_2d, pending, planned, tight_planned = [], [], [], [], []
for env in ENVS + ENVS_2D:
    sink = rows_2d if env in ENVS_2D else rows
    folder = run_dir(env)
    if folder is None:
        # No epoch-N checkpoint yet.  Still emit the row so the table lists every
        # cell of the benchmark rather than only the finished ones; a run that is
        # under way contributes its elapsed training seconds from the log, which
        # is why Train Time (s) can be populated while Model is still '--'.
        pending.append(env)
        loss, seconds = log_stats(env)
        sink.append((env, None,
                     '{:.4e}'.format(loss) if loss is not None else '--',
                     '{:.0f}'.format(seconds) if seconds is not None else '--',
                     hms(seconds) if seconds is not None else '--',
                     '--', '--', '--', '--'))
        continue
    loss, seconds = log_stats(env)
    plan = plan_stats(args.planPath, env_dir(env))
    if plan is None:
        rate = ptime = plen = '--'
    else:
        rate = '{:.1%} ({}/{})'.format(plan[0], plan[5], plan[6])
        ptime = '{:.3f} ± {:.3f}'.format(plan[1], plan[2])
        plen = '{:.3f} ± {:.3f}'.format(plan[3], plan[4])
        planned.append(env)
    tight = plan_stats(args.tightPlanPath, env_dir(env) + '_tight')
    if tight is None:
        trate = '--'
    else:
        trate = '{:.1%} ({}/{})'.format(tight[0], tight[5], tight[6])
        tight_planned.append(env)
    sink.append((env,
                 os.path.join(folder, 'latest.pt'),
                 '{:.4e}'.format(loss) if loss is not None else '--',
                 '{:.0f}'.format(seconds) if seconds is not None else '--',
                 hms(seconds) if seconds is not None else '--',
                 rate, ptime, plen, trate))

