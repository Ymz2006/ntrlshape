    'unchanged. `Tshape3d_env4` is the (`Tshape3d`, `2denv4`) 2-D cell under its',
    'pre-env-tag name, which is why the 2-D block lists six `2denv4` rows, not seven.',
    'All 28 2-D datasets exist, with both test-set variants -- standard',
    '(`--offset 0.02`) and `_tight` (`--offset 0.005`) -- see `../../2d_gen_times.md`.',
    '',
    'The table is split into a 3-D and a 2-D section. Every cell of the benchmark',
    'gets a row, trained or not. A row whose `Model` is',
    '`--` has no epoch-{} checkpoint yet; if its `Train Time (s)` is filled while'.format(args.epochs),
    '`Model` is still `--`, that is a run currently under way, and the figure is',
    'elapsed-so-far rather than final. `Train Time (s)` is the training time of that',
    'cell, parsed from `<modelPath>/logs/<env>.log`.',
    '',
